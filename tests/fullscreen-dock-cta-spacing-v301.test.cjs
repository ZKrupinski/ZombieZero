'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('dist/index.html','utf8');
const css=fs.readFileSync('dist/garage.css','utf8');
const worker=fs.readFileSync('dist/sw.js','utf8');
const app=fs.readFileSync('dist/app.js','utf8');
assert.match(html,/garage\.css\?v=[^"]*v301-fullscreen-dock-gap/,'CSS must reload on mobile');
assert.match(worker,/v301-fullscreen-dock-gap/,'offline app cache refresh');
assert.match(app,/const fn=root.requestFullscreen\|\|root.webkitRequestFullscreen/,'fullscreen element is the document root');
const mark=css.lastIndexOf('/* v301 — The native fullscreen viewport');
assert(mark>0,'full-screen-only override found');
const block=css.slice(mark);
assert.match(block,/html:fullscreen #overlay\[data-screen="selection"\] #heroes\{/);
assert.match(block,/flex:0 0 calc\(30% - 12px \* var\(--ui-scale,1\)\)!important/);
assert.match(block,/height:calc\(30% - 12px \* var\(--ui-scale,1\)\)!important/);
assert.match(block,/max-height:calc\(30% - 12px \* var\(--ui-scale,1\)\)!important/);
assert.match(block,/margin-top:calc\(-3px \* var\(--ui-scale,1\)\)!important/);
assert(!block.includes('#main-dock{')&&!block.includes('bottom:calc('),'dock icon size/anchor remain untouched');
assert(!block.includes('[data-screen="results"]')&&!block.includes('[data-screen="pause"]'),'other menus untouched');
const oldDock=css.slice(css.lastIndexOf('/* v300 — Identical lower menu dock'),mark);
assert.match(oldDock,/bottom:calc\(54px \* var\(--ui-scale,1\)\)!important/);
assert.match(oldDock,/height:calc\(93px \* var\(--ui-scale,1\)\)!important/);
assert.match(oldDock,/width:min\(96%,calc\(83px \* var\(--ui-scale,1\)\)\)!important/);
for(const scale of [.72,.9,1,1.5,1.68]){
 const boardHeight=710*scale;
 const heroHeightBefore=.30*boardHeight,heroHeightAfter=heroHeightBefore-12*scale;
 const heroShift=3*scale;
 const iconDockTop=boardHeight-(54+93)*scale;
 assert(heroHeightAfter>180*scale,'reel remains comfortably tall');
 assert(Math.abs((heroHeightBefore-heroHeightAfter+heroShift)/scale-15)<1e-8,'upper CTA gets 15 logical px more clearance');
 assert(Math.abs(iconDockTop/scale-563)<1e-8,'identical dock position in fullscreen and windowed');
}
console.log('PASS v301: ENDLESS WAVE clears icon dock by 15 additional board pixels fullscreen-only; windowed dock unaffected');
