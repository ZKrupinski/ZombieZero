'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),crypto=require('node:crypto'),path=require('node:path');
const html=fs.readFileSync('dist/index.html','utf8');
const css=fs.readFileSync('dist/upgrade-ui-v198.css','utf8');
const growth=fs.readFileSync('dist/progression.js','utf8');
const sw=fs.readFileSync('dist/sw.js','utf8');
const root='dist/assets/ui/';
const original=fs.readFileSync(root+'upgrade-atlas-v198.png');
assert.equal(original.subarray(0,8).toString('hex'),'89504e470d0a1a0a','source must be transparent PNG');
assert.equal(original.readUInt32BE(16),1448,'original source atlas width');
assert.equal(original.readUInt32BE(20),1086,'original source atlas height');
assert.equal(crypto.createHash('sha256').update(original).digest('hex'),'8501871d56190d4994f6e0dfbf1bf6e1805d08a5fe92bad2a86fcff97f468475','approved source must not change');
const manifest=JSON.parse(fs.readFileSync(root+'upgrade-atlas-v198-manifest.json','utf8'));
assert.equal(Object.keys(manifest.assets).length,21,'all source UI parts are sliced');
for(const [name,asset] of Object.entries(manifest.assets)){
 const filename=root+asset.file;
 assert(fs.existsSync(filename),'missing cutout '+name);
 const bytes=fs.readFileSync(filename);
 assert.equal(bytes.toString('ascii',0,4),'RIFF','valid WebP container '+name);
 assert.equal(bytes.toString('ascii',8,12),'WEBP','valid WebP file '+name);
 assert(asset.size[0]>0&&asset.size[1]>0,'crop dimensions for '+name);
 assert(css.includes("upgrade-"+name+"-v198.webp"),'cutout actually styled in game UI '+name);
}
assert(html.includes('upgrade-ui-v198.css?v=198-approved-atlas-slices'),'last-loaded atlas stylesheet');
assert(html.indexOf('upgrade-ui-v198.css?v=')>html.indexOf('style.css?v='),'approved art CSS overrides old UI');
assert(growth.includes('funnyNames')&&growth.includes('skillJokes'),'23 comic skill names and explanations');
assert(growth.includes('buy.textContent=max'),'cost remains dynamic instead of baked into image');
assert(html.includes('id="upgrade-detail-buy"'),'functional purchase button is preserved');
assert(growth.includes('list.innerHTML=GROUPS.map(group=>'),'all 23 skills remain in 3 columns');
assert(!html.includes('id="upgrade-tabs"')&&!html.includes('upgrade-page-prev'),'no growth tab or paging');
assert(css.includes('assets/ip/item-icons-v56.png'),'weapon icon artwork remains the existing game sprite');
assert(css.includes('zz-original-heroes')&&css.includes('zz-original-zombies'),'character art comes from existing game sprites');
assert(sw.includes("'./upgrade-ui-v198.css'"),'PWA caches style');
for(const item of Object.values(manifest.assets))assert(sw.includes("'./assets/ui/"+item.file+"'"),'PWA contains cutout '+item.file);
console.log('PASS v198: exact approved PNG atlas, 21 bitmap cutouts, runtime UI references, original skill/cast art, dynamic upgrades, PWA assets');
