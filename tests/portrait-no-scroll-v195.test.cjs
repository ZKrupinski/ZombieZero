'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync('dist/index.html','utf8');
const css=fs.readFileSync('dist/style.css','utf8');
const app=fs.readFileSync('dist/app.js','utf8');
const progression=fs.readFileSync('dist/progression.js','utf8');
const helper=fs.readFileSync('dist/menu-pages.js','utf8');
const cast=fs.readFileSync('dist/assets/ip/v2/cast-demo.js','utf8');
const sw=fs.readFileSync('dist/sw.js','utf8');
for(const [name,code] of [['progression',progression],['menu-pages',helper],['cast-demo',cast],['sw',sw]])assert.doesNotThrow(()=>new Function(code),name+' must parse');
assert(!html.includes('id="upgrade-tabs"')&&!html.includes('upgrade-page-prev'),'no upgrade tabs or page controls');
assert(html.includes('id="upgrade-detail-buy"')&&html.includes('id="upgrade-list"'),'selection/purchase layout');
assert(progression.includes('list.innerHTML=GROUPS.map(group=>'),'render all categories at once');
assert(progression.includes('defs.filter(d=>d.group===group.id)'),'every skill of each category rendered');
assert(!progression.includes('PAGE_SIZE=3'),'old upgrade pagination removed');
assert(cast.includes("const PAGE_SIZE=4")&&cast.includes("c.parentElement.hidden"),'sprite gallery shows 4 per page and pauses hidden rendering');
assert(helper.includes("dialog.addEventListener('close'")&&helper.includes("prev.addEventListener('click'")&&helper.includes("next.addEventListener('click'"),'help pages have bounded navigation');
assert(css.includes('/* v195 — 9:16 portrait page contract.'),'responsive 9:16 CSS is present');
assert(css.includes('/* v196: ALL 23 SKILLS ON ONE 9:16 SCREEN'),'all-skills CSS present');
assert(css.includes('grid-template-columns:repeat(3,minmax(0,1fr))!important'),'three columns');
assert(css.includes('grid-template-rows:22px repeat(9,minmax(0,1fr))!important'),'nine survival rows');
assert(css.includes('#upgrade-dialog #upgrade-detail-buy'),'visible buy action');
for(const rule of ['#upgrade-dialog.zz-upgrade-dialog','grid-template-rows:repeat(3,minmax(0,1fr))','#help-dialog[open]',".object-cast-card[hidden]",'html.portrait-play #overlay[data-screen="results"]', '#options-dialog .options-actions .option-tile'])assert(css.includes(rule),'missing no-scroll layout rule '+rule);
assert(html.indexOf('menu-pages.js?v=')>html.indexOf('app.js?v='),'help controller loads after app dialog controls');
assert(html.indexOf('menu-pages.js?v=')<html.indexOf('cast-demo.js?v='),'help navigation loads before sprite demo');
assert(sw.includes("'./menu-pages.js'"),'PWA keeps menu controller offline');
assert(app.includes("const scale=Math.min(width/450,height/710)"),'game world scale remains unchanged for fair physics');
console.log('PASS: 9:16 selection/results, 23-skill one-screen overview, paged guide/gallery and unchanged contained game physics');
