'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const garageSource=fs.readFileSync('dist/garage.js','utf8');
const gameSource=fs.readFileSync('dist/game.js','utf8');
const uiSource=fs.readFileSync('dist/garage-ui.js','utf8');
const css=fs.readFileSync('dist/garage.css','utf8');
const html=fs.readFileSync('dist/index.html','utf8');
const sw=fs.readFileSync('dist/sw.js','utf8');
const ctx=vm.createContext({window:{}});
vm.runInContext(garageSource,ctx);
const garage=ctx.window.ZZGarage;
garage.load(3,garage.blank());
const ball=()=>({vx:320,vy:-360,returns:0,bank:false,first:true});
const aim=hero=>garage.strike(ball(),hero,.38);
assert(Math.abs(aim(3))>Math.abs(aim(0))*1.55,'Wrench steers farther at the same paddle contact');
assert(Math.abs(aim(3))>Math.abs(aim(1))*1.4,'Wrench is more angular than Ruby');
let metal=ball();
garage.strike(metal,3,.38);
metal.bank=true; // side-wall event is produced by game.js ballImpact
const ricochet={x:-320,y:-360};
garage.contact(metal,3,ricochet);
assert.equal(ricochet.ricochet,true);
assert.equal(ricochet.y,0,'Wrench shoves sideways');
assert(ricochet.push>=2.15&&ricochet.power>=1.55,'charged hit increases push and damage');
assert.equal(metal.bank,false,'charge consumed after first enemy');
let plain=ball();garage.strike(plain,3,.38);
const plainHit={x:320,y:-360};garage.contact(plain,3,plainHit);
assert(!plainHit.ricochet,'only wall-bounced balls get shockwave');
let ruby=ball();garage.strike(ruby,1,.12);
const smash={x:120,y:-360};garage.contact(ruby,1,smash);
assert(smash.push>=1.9&&smash.power>=1.15,'Ruby center smash is a real impact buff');
let ria=ball();garage.strike(ria,2,.1);
const first={x:0,y:-360};garage.contact(ria,2,first);
assert(!first.echo,'Ria echo is not applied on the first return');
garage.strike(ria,2,.1);
const second={x:0,y:-360};garage.contact(ria,2,second);
assert(second.echo,'Ria chains every second return');
for(const name of ['GUARDIAN','SPEEDSTER','BREAKER','TRICKSHOT'])
 assert(gameSource.includes("role:'"+name+"'"),name+' class exists in gameplay config');
assert(gameSource.includes('impact?.ricochet')&&gameSource.includes('bankTargets'),'Wrench splash integrated with hit()');
assert(gameSource.includes("if(selectedHero===3&&!b.bank)effect"),'Wrench wall-charge cue integrated');
assert(gameSource.includes("if(selectedHero===3&&b.bank)"),'Wrench charged ball visual is active');
assert(uiSource.includes('hero-class-badge')&&css.includes('v267: visible per-hero class identity'));
assert(html.includes('v267-ricochet-classes')&&html.includes('v267-class-combat')&&html.includes('v267-class-badges'));
assert(sw.includes('v267-class-kits-bank-shot'),'service worker must invalidate old game');
console.log('PASS v267: Wrench aim, charged first impact, Ruby center slam, Ria second echo, class badges and PWA cache');
